import { mkdir, readFile, writeFile } from 'node:fs/promises';

// A single file for Supabase's browser editor. CLI deployments use the original
// index.ts + core.mjs directly. No secrets or public config enter this bundle.
const directory = new URL('../supabase/functions/papertone-analytics/', import.meta.url);
const output = new URL('../output/papertone-analytics/', import.meta.url);
const core = await readFile(new URL('core.mjs', directory), 'utf8');
await mkdir(output, { recursive: true });
await writeFile(new URL('index.ts', output), `// Generated by scripts/bundle-visitor-function.mjs. Do not edit here.\n// @ts-nocheck -- core.mjs is JavaScript, tested independently in Node.\n${core}\nDeno.serve(createHandler(readConfig((name) => Deno.env.get(name))));\n`);
console.log(`Supabase browser-editor bundle: ${new URL('index.ts', output).pathname}`);
